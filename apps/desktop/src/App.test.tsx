import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { expect, it, vi } from 'vitest';
import { createBrowserAdapter } from './browser-adapter';
import { App } from './App';
it('navega de onboarding a extractos citados y al documento', async () => {
  const user = userEvent.setup();
  render(<App api={createBrowserAdapter()} native={false}/>);
  expect(screen.getByRole('heading', {name:'Tu archivo. A mano.'})).toBeInTheDocument();
  expect(screen.getByRole('button',{name:/Elegir carpeta/})).toBeDisabled();
  await user.click(screen.getByRole('button',{name:'Cargar demo'}));
  await screen.findByRole('heading',{name:'Encuentra el detalle.'});
  await user.type(screen.getByLabelText('Buscar o preguntar en el archivo'),'electricidad');
  await user.click(screen.getByRole('button',{name:'Buscar extractos'}));
  await user.click(await screen.findByRole('button',{name:'Factura de electricidad'}));
  expect(await screen.findByRole('heading',{name:'Factura de electricidad'})).toBeInTheDocument();
  expect(screen.getByText(/42 euros/)).toBeInTheDocument();
  expect(screen.getByText(/Página 1/)).toBeInTheDocument();
});
it('marca duplicados y exportación como pendientes y borra la demo con confirmación', async () => {
  const api = createBrowserAdapter();
  await api.demoLoad();
  const user = userEvent.setup();
  render(<App api={api} native={false}/>);
  await user.click(screen.getByRole('button',{name:'Duplicados'}));
  expect(screen.getByText('Detección de duplicados · Pendiente')).toBeInTheDocument();
  await user.click(screen.getByRole('button',{name:'Ajustes'}));
  expect(screen.getByRole('button',{name:'Exportar índice · Pendiente'})).toBeDisabled();
  vi.spyOn(window,'confirm').mockReturnValue(false);
  await user.click(screen.getByRole('button',{name:'Borrar demo'}));
  expect(await api.indexStatus()).toMatchObject({files:3});
  vi.spyOn(window,'confirm').mockReturnValue(true);
  await user.click(screen.getByRole('button',{name:'Borrar demo'}));
  await screen.findByText('Índice vacío');
  expect(await api.indexStatus()).toMatchObject({files:0});
});
it('muestra loading, no encontrado y error sin inventar contenido', async () => {
  const api = createBrowserAdapter(); await api.demoLoad();
  let resolveSearch!: (value: []) => void;
  api.search = () => new Promise(resolve => {resolveSearch = resolve;});
  const user = userEvent.setup(); render(<App api={api} native={false}/>);
  await user.click(screen.getByRole('button',{name:'Buscar'}));
  await user.type(screen.getByLabelText('Buscar o preguntar en el archivo'),'desconocido');
  await user.click(screen.getByRole('button',{name:'Buscar extractos'}));
  expect(screen.getByRole('status')).toHaveTextContent('Procesando en local');
  resolveSearch([]);
  await screen.findByText('No encontrado');
  api.search = async () => {throw new Error('backend falló');};
  await user.click(screen.getByRole('button',{name:'Buscar extractos'}));
  await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('No se pudo completar la búsqueda'));
  expect(screen.queryByText('No encontrado')).not.toBeInTheDocument();
});
it('pide confirmación modal dentro de la aplicación nativa', async () => {
  const api = createBrowserAdapter(); await api.demoLoad();
  const user = userEvent.setup(); render(<App api={api} native={true}/>);
  await user.click(screen.getByRole('button',{name:'Ajustes'}));
  await user.click(screen.getByRole('button',{name:'Borrar índice'}));
  expect(screen.getByRole('dialog',{name:'¿Borrar el índice local?'})).toBeInTheDocument();
  await user.click(screen.getByRole('button',{name:'Cancelar'}));
  expect(await api.indexStatus()).toMatchObject({files:3});
  await user.click(screen.getByRole('button',{name:'Borrar índice'}));
  await user.click(screen.getByRole('button',{name:'Sí, borrar índice'}));
  await screen.findByText('Índice vacío');
  expect(await api.indexStatus()).toMatchObject({files:0});
});
